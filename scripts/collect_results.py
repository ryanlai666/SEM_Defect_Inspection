        fs.setdefault(rname, {})["full"] = [m["macro_f1"] for m in rs]
        fs4.setdefault(rname, {})["full"] = [macro4(m) for m in rs]
        rep_cm.setdefault(rname, {})["full"] = (rs[0]["confusion_matrix"], rs[0]["labels"])
