"""Aggregate finished runs into the report tables -> docs/results.md and outputs/results_summary.json.

Every number comes from outputs/<run>/*.json|npz; missing runs show "—" (never imputed).
Conventions: mean ± sample std (ddof=1) over seeds; 95 % percentile bootstrap CIs over
test images (2,000 resamples) from the saved confusion matrices / per-image scores; per-class test support
counts shown next to every per-class number; a training-free high-pass baseline in every anomaly table.

    python scripts/collect_results.py
"""

