N_BOOT = 2000


def jload(p: Path):
    return json.loads(p.read_text()) if p.exists() else None


def clean(vals) -> np.ndarray:
    return np.asarray([x for x in vals if x is not None and np.isfinite(x)], dtype=float)


def ms(vals, nd=3) -> str:
    v = clean(vals)
    if v.size == 0:
        return "—"
    if v.size == 1:
        return f"{v[0]:.{nd}f}"
    return f"{v.mean():.{nd}f} ± {v.std(ddof=1):.{nd}f} (n={v.size})"


def stats(vals) -> dict | None:
    v = clean(vals)
    if v.size == 0:
        return None
    return {
        "mean": float(v.mean()),
        "std": float(v.std(ddof=1)) if v.size > 1 else 0.0,
        "n": int(v.size),
        "values": v.tolist(),
    }


def ci_str(ci) -> str:
    return "—" if ci is None else f"[{ci[0]:.3f}, {ci[1]:.3f}]"


# ----------------------------------------------------------------------------- bootstrap helpers
def _f1_macro_from_pairs(t: np.ndarray, p: np.ndarray, labels: list[int]) -> float:
    f1 = []
    for c in labels:
        tp = np.sum((t == c) & (p == c))
        fp = np.sum((t != c) & (p == c))
        fn = np.sum((t == c) & (p != c))
        f1.append(0.0 if tp == 0 else 2 * tp / (2 * tp + fp + fn))
    return float(np.mean(f1))


def boot_macro_f1(
    cm: list[list[int]], labels: list[int], subset: list[int] | None = None
) -> tuple[float, float]:
    """Image-level bootstrap of macro-F1 from a confusion matrix (rows = true, cols = predicted)."""
    cm = np.asarray(cm)
    t = np.repeat(np.repeat(labels, cm.shape[1]), cm.ravel())
    p = np.repeat(np.tile(labels, cm.shape[0]), cm.ravel())
    rng = np.random.default_rng(0)
    sub = subset or labels
    vals = [
        _f1_macro_from_pairs(t[i], p[i], sub)
        for i in (rng.integers(0, t.size, t.size) for _ in range(N_BOOT))
    ]
    return float(np.percentile(vals, 2.5)), float(np.percentile(vals, 97.5))


def boot_auroc(scores: np.ndarray, labels: np.ndarray) -> tuple[float, float] | None:
    from sklearn.metrics import roc_auc_score

    if labels.min() == labels.max():
        return None
    rng = np.random.default_rng(0)
    pos, neg = np.where(labels == 1)[0], np.where(labels == 0)[0]
    vals = []
    for _ in range(N_BOOT):  # stratified: keep both classes present
        i = np.concatenate([rng.choice(pos, pos.size), rng.choice(neg, neg.size)])
        vals.append(roc_auc_score(labels[i], scores[i]))
    return float(np.percentile(vals, 2.5)), float(np.percentile(vals, 97.5))


def boot_mean(x: np.ndarray) -> tuple[float, float] | None:
    if x.size == 0:
        return None
    rng = np.random.default_rng(0)
    vals = [x[rng.integers(0, x.size, x.size)].mean() for _ in range(N_BOOT)]
    return float(np.percentile(vals, 2.5)), float(np.percentile(vals, 97.5))


def macro4(m: dict) -> float:
    return float(np.mean([m["per_class_f1"][c] for c in MAJOR]))


def runs(pattern: str, section: str | None = None) -> list[tuple[str, dict]]:
    """(run dir, metrics) for run dirs matching `pattern`; `section` picks a sub-dict of test_metrics.json
    (the Colab YOLO26n-seg run stores its segmentation / anomaly / classification results side by side)."""
    rx = re.compile(pattern)
    out = []
    for d in sorted(OUT.iterdir()) if OUT.exists() else []:
        if d.is_dir() and rx.fullmatch(d.name):
            m = jload(d / "test_metrics.json")
            if m is not None:
                m = m.get(section) if section else m.get("test", m)
                if m:
                    out.append((d.name, m))
    return out


